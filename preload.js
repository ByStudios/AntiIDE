const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  ping: () => ipcRenderer.invoke('ping'),
  jdkList: () => ipcRenderer.invoke('jdk:list'),
  jdkVersions: () => ipcRenderer.invoke('jdk:versions'),
  jdkInstall: (v) => ipcRenderer.invoke('jdk:install', v),
  jdkSetActive: (p) => ipcRenderer.invoke('jdk:setActive', p),
  jdkGetProject: () => ipcRenderer.invoke('jdk:getProject'),
  saveSettings: (o) => ipcRenderer.invoke('project:saveSettings', o),
  onJdkProgress: (cb) => ipcRenderer.on('jdk:progress', (e, d) => cb(d)),
  defaultLocation: () => ipcRenderer.invoke('path:defaultLocation'),
  pickParent: () => ipcRenderer.invoke('dialog:pickParent'),
  newProject: (cfg) => ipcRenderer.invoke('project:new', cfg),
  openFolder: () => ipcRenderer.invoke('dialog:openFolder'),
  createProject: (parentDir, name) => ipcRenderer.invoke('project:create', parentDir, name),
  createProjectHere: (name) => ipcRenderer.invoke('project:createHere', name),
  list: (root) => ipcRenderer.invoke('fs:list', root),
  read: (fp) => ipcRenderer.invoke('fs:read', fp),
  write: (fp, c) => ipcRenderer.invoke('fs:write', fp, c),
  create: (base, name, isDir) => ipcRenderer.invoke('fs:create', base, name, isDir),
  del: (fp) => ipcRenderer.invoke('fs:delete', fp),
  rename: (o, n) => ipcRenderer.invoke('fs:rename', o, n),
  runFile: (fp) => ipcRenderer.invoke('run:file', fp),
  termExec: (cwd, cmd) => ipcRenderer.invoke('term:exec', cwd, cmd),
  gitExec: (cwd, args) => ipcRenderer.invoke('git:exec', cwd, args),
  onFolderOpened: (cb) => ipcRenderer.on('folder:opened', (e, p) => cb(p)),
  onMenu: (name, cb) => ipcRenderer.on(name, cb),
});
